void draw_text(ctr::Framebuffer& fb, int x, int y, const char* text, uint32_t argb, int scale) {
    for (const char* p = text; *p; ++p, x += 6 * scale) {
        unsigned c = (unsigned char)*p;
        if (c < 0x20 || c > 0x7E) c = '?';
        const uint8_t* g = kFont[c - 0x20];
        for (int cx = 0; cx < 5; ++cx)
            for (int cy = 0; cy < 8; ++cy)
                if (g[cx] & (1 << cy))
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx) {
                            int px = x + cx * scale + sx, py = y + cy * scale + sy;
                            if (px >= 0 && py >= 0 && px < fb.width && py < fb.height)
                                fb.pixels[size_t(py) * fb.width + px] = argb;
                        }
    }
}

bool App::init() { return plat_.init() == ctr::kResultSuccess; }
void App::shutdown() { plat_.shutdown(); }

static void fill(ctr::Framebuffer& fb, uint32_t c) { for (auto& p : fb.pixels) p = c; }

// Centre text using the reconstructed original strlen.
static void draw_centered(ctr::Framebuffer& fb, int y, const char* s, uint32_t c) {
    int w = eshop_orig::cstring_length(s) * 6;
    draw_text(fb, (fb.width - w) / 2, y, s, c);
}

void App::frame() {
    plat_.hid_scan();
    const ctr::HidState& h = plat_.hid();
    ctr::Framebuffer& t = plat_.top();
    ctr::Framebuffer& b = plat_.bottom();
    fill(t, 0xFF1B2A41u);
    fill(b, 0xFF223344u);

    // UTF-16 label: stands in for a message-catalog string; length via original routine.
    static const uint16_t kTitle16[] = {'e','S','h','o','p',' ','L','i','n','u','x',' ','P','o','r','t',0};
    char title[64];
    eshop_orig::cstring_copy(title, "");
    char num[16];
    std::snprintf(num, sizeof num, "%d", eshop_orig::string16_length(kTitle16));
    eshop_orig::cstring_append(title, "eShop Linux Port  (title16 len ");
    eshop_orig::cstring_append(title, num);
    eshop_orig::cstring_append(title, ")");
    draw_centered(t, 20, title, 0xFFFFFFFFu);
    draw_centered(t, 40, "BRING-UP SCREEN - not the original eShop UI", 0xFFFFC857u);
    draw_text(t, 16, 70, "Reconstructed original routines in use:", 0xFFB0C4DEu);
    draw_text(t, 24, 86, "cstring_copy/append @002A8F1C/@00100186", 0xFFFFFFFFu);
    draw_text(t, 24, 98, "cstring_length      @002A8F8C", 0xFFFFFFFFu);
    draw_text(t, 24, 110, "string16_length     @002A0964", 0xFFFFFFFFu);
    draw_text(t, 16, 140, "Everything else here is a substitute.", 0xFFFFC857u);
    draw_text(t, 16, 160, "See docs/FUNCTION_PORT_STATUS.md", 0xFFB0C4DEu);

    char line[96];
    std::snprintf(line, sizeof line, "frame %llu", (unsigned long long)frames_);
    draw_text(t, 8, 226, line, 0xFF8899AAu);

    draw_centered(b, 12, "Touch / input test", 0xFFFFFFFFu);
    std::snprintf(line, sizeof line, "held=%03x down=%03x up=%03x", h.held, h.down, h.up);
    draw_text(b, 12, 36, line, 0xFFB0C4DEu);
    if (h.touching) {
        std::snprintf(line, sizeof line, "touch %d,%d", h.touch_x, h.touch_y);
        draw_text(b, 12, 52, line, 0xFF7CFC00u);
        for (int d = -4; d <= 4; ++d) {
            int px = h.touch_x + d, py = h.touch_y;
            if (px >= 0 && px < b.width) b.pixels[size_t(py) * b.width + px] = 0xFF7CFC00u;
            px = h.touch_x; py = h.touch_y + d;
            if (py >= 0 && py < b.height) b.pixels[size_t(py) * b.width + px] = 0xFF7CFC00u;
        }
    }
    ++frames_;
}

